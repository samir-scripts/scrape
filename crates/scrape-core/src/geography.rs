//! Shared catalog for extraction and generated geography controls.
use isocountry::CountryCode;
use serde::{Deserialize, Serialize};
use std::sync::LazyLock;
use ts_rs::TS;

#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct CountryOption {
    pub code: String,
    pub name: String,
}
#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct RegionOption {
    pub code: String,
    pub name: String,
    pub country_code: String,
}

pub static REGIONS: LazyLock<Vec<RegionOption>> = LazyLock::new(|| {
    serde_json::from_str(include_str!("../data/regions.json"))
        .expect("valid checked-in subdivision catalog")
});
fn common_name(code: &str) -> Option<&'static str> {
    const NAMES: &[(&str, &str)] = &[
        ("US", "United States"),
        ("GB", "United Kingdom"),
        ("KR", "South Korea"),
        ("KP", "North Korea"),
        ("RU", "Russia"),
        ("CZ", "Czechia"),
        ("TW", "Taiwan"),
        ("TR", "Türkiye"),
        ("VN", "Vietnam"),
        ("TZ", "Tanzania"),
        ("IR", "Iran"),
        ("SY", "Syria"),
        ("MD", "Moldova"),
        ("BO", "Bolivia"),
        ("VE", "Venezuela"),
    ];
    NAMES
        .iter()
        .find(|(value, _)| *value == code)
        .map(|(_, name)| *name)
}
pub fn countries() -> Vec<CountryOption> {
    let mut result: Vec<_> = CountryCode::iter()
        .map(|country| CountryOption {
            code: country.alpha2().into(),
            name: common_name(country.alpha2())
                .unwrap_or(country.name())
                .into(),
        })
        .collect();
    result.sort_by(|a, b| a.name.cmp(&b.name));
    result
}
pub fn normalize(value: &str) -> String {
    value
        .to_uppercase()
        .chars()
        .map(|c| match c {
            '\u{0300}'..='\u{036f}' => String::new(),
            'À' | 'Á' | 'Â' | 'Ã' | 'Ä' | 'Å' => "A".into(),
            'Ç' => "C".into(),
            'È' | 'É' | 'Ê' | 'Ë' => "E".into(),
            'Ì' | 'Í' | 'Î' | 'Ï' => "I".into(),
            'Ñ' => "N".into(),
            'Ò' | 'Ó' | 'Ô' | 'Õ' | 'Ö' | 'Ø' => "O".into(),
            'Ù' | 'Ú' | 'Û' | 'Ü' => "U".into(),
            'Ý' | 'Ÿ' => "Y".into(),
            '&' => " AND ".into(),
            c if c.is_alphanumeric() => c.to_string(),
            _ => " ".into(),
        })
        .collect::<String>()
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}
pub fn contains_phrase(value: &str, phrase: &str) -> bool {
    format!(" {} ", normalize(value)).contains(&format!(" {} ", normalize(phrase)))
}
/// Exact country fields, never substring matches (e.g. India inside Indiana).
pub fn country_code(value: &str) -> Option<String> {
    let name = normalize(value);
    let alias = match name.as_str() {
        "USA" | "U S" | "U S A" | "UNITED STATES" | "UNITED STATES OF AMERICA" => Some("US"),
        "UK" | "U K" | "GREAT BRITAIN" | "UNITED KINGDOM" => Some("GB"),
        "UAE" => Some("AE"),
        "DEUTSCHLAND" => Some("DE"),
        "TURKEY" | "TURKIYE" => Some("TR"),
        _ => None,
    };
    if let Some(code) = alias {
        return Some(code.into());
    }
    static NAMES: LazyLock<std::collections::HashMap<String, String>> = LazyLock::new(|| {
        CountryCode::iter()
            .flat_map(|country| {
                [
                    country.alpha2().to_string(),
                    country.alpha3().to_string(),
                    normalize(country.name()),
                    normalize(common_name(country.alpha2()).unwrap_or(country.name())),
                ]
                .into_iter()
                .map(move |key| (key, country.alpha2().to_string()))
            })
            .collect()
    });
    NAMES.get(&name).cloned()
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn export_bindings_geography_catalog() {
        let values = serde_json::json!({"countries": countries(), "regions": *REGIONS});
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../src/bindings/geographyCatalog.ts");
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, format!("// Generated by scrape-core; do not edit.\nexport const GEOGRAPHY_CATALOG = {} as const;\n", serde_json::to_string_pretty(&values).unwrap())).unwrap();
    }
    #[test]
    fn catalog_codes_are_unique_and_aliases_are_exact() {
        assert_eq!(countries().len(), 249);
        let mut seen = std::collections::HashSet::new();
        for region in REGIONS.iter() {
            assert!(seen.insert(format!("{}-{}", region.country_code, region.code)));
            assert_eq!(
                country_code(&region.country_code).as_deref(),
                Some(region.country_code.as_str())
            );
        }
        assert_eq!(country_code("U.S.A.").as_deref(), Some("US"));
        assert_eq!(country_code("UK").as_deref(), Some("GB"));
        assert_eq!(country_code("Remoteville"), None);
        assert!(!contains_phrase("Indiana", "India"));
    }
}
