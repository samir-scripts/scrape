//! Pinned BLS occupation and O*NET technology-title catalog.
use serde::{Deserialize, Serialize};
use std::sync::LazyLock;
use ts_rs::TS;

#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct OccupationCatalog {
    pub version: String,
    pub groups: Vec<OccupationGroup>,
    pub occupations: Vec<Occupation>,
    pub titles: Vec<OccupationTitle>,
    pub attribution: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct OccupationGroup {
    pub code: String,
    pub name: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct Occupation {
    pub soc_code: String,
    pub title: String,
    pub group_code: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum OccupationTitleOrigin {
    Bls,
    Onet,
}

#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct OccupationTitle {
    pub label: String,
    pub soc_codes: Vec<String>,
    pub onetsoc_codes: Vec<String>,
    pub source_codes: Vec<String>,
    pub origin: OccupationTitleOrigin,
}

pub static OCCUPATION_CATALOG: LazyLock<OccupationCatalog> = LazyLock::new(|| {
    let catalog: OccupationCatalog =
        serde_json::from_str(include_str!("../data/occupations/catalog.json"))
            .expect("valid checked-in occupation catalog");
    assert_eq!(catalog.groups.len(), 23);
    let groups: std::collections::HashSet<_> = catalog
        .groups
        .iter()
        .map(|group| group.code.as_str())
        .collect();
    assert_eq!(groups.len(), catalog.groups.len());
    assert_eq!(catalog.occupations.len(), 867);
    let occupations: std::collections::HashSet<_> = catalog
        .occupations
        .iter()
        .map(|occupation| occupation.soc_code.as_str())
        .collect();
    assert_eq!(occupations.len(), catalog.occupations.len());
    assert!(catalog
        .occupations
        .iter()
        .all(|occupation| groups.contains(occupation.group_code.as_str())));
    assert!(catalog
        .titles
        .iter()
        .all(|title| !title.label.trim().is_empty()
            && !title.soc_codes.is_empty()
            && title
                .soc_codes
                .iter()
                .all(|code| occupations.contains(code.as_str()))
            && match title.origin {
                OccupationTitleOrigin::Bls =>
                    title.onetsoc_codes.is_empty() && title.source_codes.is_empty(),
                OccupationTitleOrigin::Onet =>
                    !title.onetsoc_codes.is_empty() && !title.source_codes.is_empty(),
            }));
    catalog
});

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn export_bindings_occupation_catalog() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../src/bindings/occupationCatalogData.ts");
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, format!(
            "// Generated by scrape-core; do not edit.\nexport const OCCUPATION_CATALOG = {} as const;\n",
            serde_json::to_string_pretty(&*OCCUPATION_CATALOG).unwrap()
        )).unwrap();
    }

    #[test]
    fn catalog_preserves_official_and_alternate_provenance() {
        assert_eq!(OCCUPATION_CATALOG.groups.len(), 23);
        assert_eq!(OCCUPATION_CATALOG.occupations.len(), 867);
        assert!(OCCUPATION_CATALOG
            .occupations
            .iter()
            .any(|occupation| occupation.soc_code == "15-1252"
                && occupation.title == "Software Developers"));
        assert!(OCCUPATION_CATALOG
            .titles
            .iter()
            .any(|title| title.label == "Data Engineer"
                && title.origin == OccupationTitleOrigin::Onet
                && title.soc_codes.len() > 1));
        assert!(OCCUPATION_CATALOG
            .titles
            .iter()
            .any(|title| title.label.contains(',') && title.origin == OccupationTitleOrigin::Bls));
    }
}
