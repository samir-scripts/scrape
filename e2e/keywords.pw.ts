import { readFile } from "node:fs/promises";
import { test, expect } from "./fixtures";
import { contrastFailures, indicatorContrast } from "./contrast";
for (const theme of ["paper", "obsidian"]) {
  test(`keyword chips retain typed phrases and All mode through save and reopen in ${theme}`, async ({ page }) => {
    await page.setViewportSize({ width: 1024, height: 900 });
    await page.goto("/?demo=1&fixtures=1");
    await page.getByRole("button", { name: "SETTINGS", exact: true }).click();
    if (theme === "obsidian") await page.getByRole("button", { name: /^OBSIDIAN/ }).click();
    await expect(page.locator("html")).toHaveAttribute("data-theme", theme);
    await page.getByRole("button", { name: "SCRAPER", exact: true }).click();
    await page.getByRole("button", { name: "Add workflow", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "Create workflow" });
    await dialog.getByRole("textbox", { name: "Source URL or board identifier" }).fill("https://boards.greenhouse.io/keyword-fixture");
    await dialog.getByRole("button", { name: "Continue to Matching" }).click();
    const input = dialog.getByRole("textbox", { name: "Keywords", exact: true });
    await input.pressSequentially("Engineer,Developer");
    await input.press("Enter");
    await dialog.getByRole("button", { name: "Match keywords" }).click();
    await page.getByRole("option", { name: "All keywords", exact: true }).click();
    await input.pressSequentially("Machine Learning");
    await dialog.getByRole("button", { name: "Continue to Schedule" }).click();
    await dialog.getByRole("button", { name: "Review workflow" }).click();
    await dialog.getByRole("button", { name: "Preview matches" }).click();
    await expect(dialog.getByRole("button", { name: "Save workflow" })).toBeEnabled();
    await dialog.getByRole("button", { name: "Save workflow" }).click();
    await dialog.getByRole("button", { name: "Done", exact: true }).click();
    const row = page.getByRole("row").filter({ hasText: "keyword-fixture" });
    await row.getByRole("button", { name: "Edit workflow keyword-fixture" }).click();
    const edit = page.getByRole("dialog", { name: "Edit workflow" });
    await edit.getByRole("button", { name: "Continue to Matching" }).click();
    await expect(edit.getByRole("button", { name: "Match keywords" })).toHaveText("All keywords");
    for (const term of ["Engineer", "Developer", "Machine Learning"]) await expect(edit.getByRole("button", { name: `Remove ${term} from Keywords`, exact: true })).toBeVisible();
    await expect(edit.getByRole("textbox", { name: "Keywords", exact: true })).toHaveValue("");
    expect(await contrastFailures(page)).toEqual([]);
    const remove = edit.getByRole("button", { name: "Remove Engineer from Keywords", exact: true });
    await remove.focus(); await page.keyboard.press("Tab"); await page.keyboard.press("Shift+Tab");
    await expect(remove).toBeFocused();
    expect(await indicatorContrast(remove, "outlineColor")).toBeGreaterThanOrEqual(3);
    await page.screenshot({ path: `/tmp/scrape-keywords-${theme}-1024.png` });
    await page.setViewportSize({ width: 480, height: 720 });
    await expect(edit.getByRole("button", { name: "Add keyword to Keywords" })).toBeInViewport();
    const overflow = await edit.evaluate(dialog => dialog.scrollWidth > dialog.clientWidth + 1);
    expect(overflow).toBe(false);
    await page.screenshot({ path: `/tmp/scrape-keywords-${theme}-480.png` });
    await edit.getByRole("textbox", { name: "Keywords", exact: true }).fill("Distributed Systems");
    await edit.getByRole("button", { name: "Advanced settings", exact: true }).click();
    const exported = page.waitForEvent("download");
    await edit.getByRole("button", { name: "Export YAML", exact: true }).click();
    const download = await exported;
    expect(await readFile((await download.path())!, "utf8")).toContain("Distributed Systems");
    await edit.getByRole("textbox", { name: "Keywords", exact: true }).fill(Array.from({ length: 100 }, (_, i) => `Keyword ${i}`).join(","));
    await edit.getByRole("textbox", { name: "Keywords", exact: true }).press("Enter");
    await expect(edit.getByRole("button", { name: /^Remove .* from Keywords$/ })).toHaveCount(104);
    const list = edit.getByRole("list", { name: "Keywords terms" });
    expect(await list.evaluate(list => list.scrollHeight > list.clientHeight)).toBe(true);
    expect(await list.evaluate(list => list.scrollWidth <= list.clientWidth + 1)).toBe(true);

  });
}
