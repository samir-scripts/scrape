import { readFile } from "node:fs/promises";
import { test, expect } from "./fixtures";
import { contrastFailures, indicatorContrast } from "./contrast";
for (const theme of ["paper", "obsidian"]) {
  test(`keyword chips retain typed phrases and independent groups through save and reopen in ${theme}`, async ({ page }) => {
    await page.setViewportSize({ width: 1024, height: 900 });
    await page.goto("/?demo=1&fixtures=1");
    await page.getByRole("button", { name: "SETTINGS", exact: true }).click();
    if (theme === "obsidian") await page.getByRole("button", { name: /^OBSIDIAN/ }).click();
    await expect(page.locator("html")).toHaveAttribute("data-theme", theme);
    await page.getByRole("button", { name: "SCRAPER", exact: true }).click();
    await page.getByRole("button", { name: "Add workflow", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "Create workflow" });
    await dialog.getByRole("textbox", { name: "Workflow name", exact: true }).fill("keyword-fixture");
    await expect(dialog.getByRole("textbox", { name: "Target roles", exact: true })).toBeVisible();
    await expect(dialog.getByRole("textbox", { name: "Companies (Optional)", exact: true })).toBeVisible();
    await expect(dialog.getByRole("button", { name: "Match keywords", exact: true })).toHaveCount(0);
    await dialog.getByRole("textbox", { name: "Any keywords", exact: true }).fill("Software");
    await dialog.getByRole("textbox", { name: "Exclude keywords", exact: true }).fill("Senior");
    const input = dialog.getByRole("textbox", { name: "All keywords", exact: true });
    await input.pressSequentially("Engineer,Developer");
    await input.press("Enter");
    await expect(dialog.getByRole("textbox", { name: "Any keywords", exact: true })).toBeVisible();
    await expect(dialog.getByRole("textbox", { name: "Exclude keywords", exact: true })).toBeVisible();
    await input.pressSequentially("Machine Learning");
    await dialog.getByRole("button", { name: "Continue to Criteria" }).click();
    // Synthetic previews cannot establish publication-date extraction.
    await dialog.getByRole("button", { name: "Date posted range", exact: true }).click();
    await page.getByRole("option", { name: "Any time", exact: true }).click();
    await dialog.getByRole("button", { name: "Continue to Sources" }).click();
    await dialog.getByRole("button", { name: "Add source", exact: true }).click();
    await dialog.getByRole("textbox", { name: "Source 2 URL or board identifier", exact: true }).fill("https://boards.greenhouse.io/keyword-fixture");
    await dialog.getByRole("button", { name: "Remove source Cross-Company Search", exact: true }).click();
    await dialog.getByRole("button", { name: "Continue to Schedule" }).click();
    await dialog.getByRole("button", { name: "Preview matches" }).click();
    await expect(dialog.getByRole("button", { name: "Save workflow" })).toBeEnabled();
    await dialog.getByRole("button", { name: "Save workflow" }).click();
    await dialog.getByRole("button", { name: "Done", exact: true }).click();
    const row = page.getByRole("row").filter({ hasText: "keyword-fixture" });
    await row.getByRole("button", { name: "Edit workflow keyword-fixture" }).click();
    const edit = page.getByRole("dialog", { name: "Edit workflow" });
    await expect(edit.getByRole("button", { name: "Remove Software from Any keywords", exact: true })).toBeVisible();
    await expect(edit.getByRole("button", { name: "Remove Senior from Exclude keywords", exact: true })).toBeVisible();
    for (const term of ["Engineer", "Developer", "Machine Learning"]) await expect(edit.getByRole("button", { name: `Remove ${term} from All keywords`, exact: true })).toBeVisible();
    await expect(edit.getByRole("textbox", { name: "All keywords", exact: true })).toHaveValue("");
    expect(await contrastFailures(page)).toEqual([]);
    const remove = edit.getByRole("button", { name: "Remove Engineer from All keywords", exact: true });
    await remove.focus(); await page.keyboard.press("Tab"); await page.keyboard.press("Shift+Tab");
    await expect(remove).toBeFocused();
    expect(await indicatorContrast(remove, "outlineColor")).toBeGreaterThanOrEqual(3);
    await page.screenshot({ path: `/tmp/scrape-keywords-${theme}-1024.png` });
    await page.setViewportSize({ width: 480, height: 720 });
    await edit.getByRole("button", { name: "Add keyword to All keywords" }).scrollIntoViewIfNeeded();
    await expect(edit.getByRole("button", { name: "Add keyword to All keywords" })).toBeInViewport();
    const overflow = await edit.evaluate(dialog => dialog.scrollWidth > dialog.clientWidth + 1);
    expect(overflow).toBe(false);
    await page.screenshot({ path: `/tmp/scrape-keywords-${theme}-480.png` });
    await edit.getByRole("textbox", { name: "All keywords", exact: true }).fill("Distributed Systems");
    await edit.getByRole("button", { name: "Advanced settings", exact: true }).click();
    const exported = page.waitForEvent("download");
    await edit.getByRole("button", { name: "Export YAML", exact: true }).click();
    const download = await exported;
    expect(await readFile((await download.path())!, "utf8")).toContain("Distributed Systems");
    await edit.getByRole("textbox", { name: "All keywords", exact: true }).fill(Array.from({ length: 100 }, (_, i) => `Keyword ${i}`).join(","));
    await edit.getByRole("textbox", { name: "All keywords", exact: true }).press("Enter");
    await expect(edit.getByRole("button", { name: /^Remove .* from All keywords$/ })).toHaveCount(104);
    const list = edit.getByRole("list", { name: "All keywords terms" });
    expect(await list.evaluate(list => list.scrollHeight > list.clientHeight)).toBe(true);
    expect(await list.evaluate(list => list.scrollWidth <= list.clientWidth + 1)).toBe(true);

  });
}
